/**
 * 围栏代码块的拆分与回拼。**一份实现两处用**：
 *
 * - 显示形（`render.ts`）靠它把围栏剥掉，只画正文；
 * - 编辑器的账本（`blocks.ts`）靠它把开栏行 / 闭栏行从正文里挪出去存进 `mdFence*`，
 *   于是"点进代码块"不再看到 Markdown，而保存时围栏按账本原样拼回去。
 *
 * 两处共用一个实现是有意的：如果"看到的正文"与"落盘的正文"由两套判据决定，
 * 分叉只是时间问题，而这里的分叉等于改用户的字节。
 */

const FENCE = /^\s{0,3}(`{3,}|~{3,})(.*)$/;

export type 围栏行 = { 记号: string; 语言: string; 可闭栏: boolean };

/**
 * 一行围栏。info 串可以是多词（`` ```rust // 注释 ``、`` ```js showLineNumbers ``），
 * 语言只取第一个词——真机栽过：早先按"一个不带空格的词"匹配整行，用户往开栏行里加一句
 * 注释，整块就静默退回源文本，看着像"渲染坏了"。
 *
 * `可闭栏` 是 CommonMark 的规矩：闭栏必须同种字符、不短于开栏、**且不带 info**。
 */
export function 围栏行of(line: string | undefined): 围栏行 | null {
  const m = FENCE.exec(line ?? "");
  if (!m) return null;
  const [, 记号 = "", 余 = ""] = m;
  const 干净 = 余.trim();
  if (记号[0] === "`" && 干净.includes("`")) return null; // 反引号围栏的 info 里不许有反引号
  return { 记号, 语言: 干净.split(/\s+/)[0] ?? "", 可闭栏: 干净 === "" };
}

export type 围栏拆 = {
  /** 开栏行，原样（含前导缩进与 info 串） */
  开: string;
  /** 围栏之间的正文行。`[]` 与 `[""]` 是两件事：前者是 ``` 紧挨 ```，后者中间有一个空行 */
  身: string[];
  /** 闭栏行；null = 没找到闭栏 */
  闭: string | null;
};

/**
 * 拆开一段围栏。首行不是开栏 → `null`（这一块不归这条路管）。
 *
 * 闭栏**从最后一行往前找**，不是往前第一处：正文里出现一道 ` ``` ` 时，文件的语义是
 * "最后一行才是闭栏"（CommonMark 与内核都这么判），显示形也照这个画。这条判据一旦被
 * 改成"就近找闭栏"，用户往代码里打一道围栏，界面上后半截就掉出代码块了。
 */
export function 拆围栏(源: string): 围栏拆 | null {
  const 行 = 源.split("\n");
  const 开 = 围栏行of(行[0]);
  // 只判"首行是不是开栏"。单独一道 ` ``` ` 也算一个（空正文的）代码块：CommonMark、
  // 内核与显示形都这么认，这里多要一个"至少两行"就把那种块打回源文本了。
  if (!开) return null;
  for (let i = 行.length - 1; i > 0; i--) {
    const 闭 = 围栏行of(行[i]);
    if (闭?.可闭栏 && 闭.记号[0] === 开.记号[0] && 闭.记号.length >= 开.记号.length) {
      return { 开: 行[0]!, 身: 行.slice(1, i), 闭: 行[i]! };
    }
  }
  // 没闭栏：按 CommonMark 就是"到文末都是代码"，内核也这么判。画可以照画，
  // 但**不许接管成"围栏在账本里"的形状**——那等于替用户凭空造一道闭栏。
  return { 开: 行[0]!, 身: 行.slice(1), 闭: null };
}

/**
 * 拆回去。`身` 为空数组时不产出中间那个换行——` ``` ` 紧挨 ` ``` ` 与"中间一个空行"
 * 是两种字节，都拼成同一个形状的话，用户删掉代码块里最后一行就会多出一个空行。
 */
export function 拼围栏(拆: { 开: string; 身: string[]; 闭: string | null }): string {
  const 身 = 拆.身.join("\n");
  if (拆.闭 === null) return 拆.身.length ? 拆.开 + "\n" + 身 : 拆.开;
  return 拆.身.length ? 拆.开 + "\n" + 身 + "\n" + 拆.闭 : 拆.开 + "\n" + 拆.闭;
}
