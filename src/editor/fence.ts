/**
 * 围栏代码块的拆分与回拼。**一份实现两处用**：
 *
 * - 显示形（`render.ts`）靠它把围栏剥掉，只画正文；
 * - 编辑器的账本（`blocks.ts`）靠它把开栏行 / 闭栏行从正文里挪出去存进 `mdFence*`，
 *   于是"点进代码块"不再看到 Markdown，而保存时围栏按账本原样拼回去。
 *
 * 两处共用一个实现是有意的：如果"看到的正文"与"落盘的正文"由两套判据决定，
 * 分叉只是时间问题，而这里的分叉等于改用户的字节。
 */

const FENCE = /^\s{0,3}(`{3,}|~{3,})(.*)$/;

/**
 * 行尾那个 `\r`。CRLF 的文件按 `\n` 切出来的每一行都带着它，而 ```` ```js\r ```` 过不了
 * `FENCE`（`.` 不认 `\r`、`$` 又不在串尾）——于是整篇 CRLF 笔记的代码块一个都不接管。
 * 判据跳过它，**存进账本的仍是原样那一行**，拼回去才是同一份字节。
 */
const 净行 = (行: string) => (行.endsWith("\r") ? 行.slice(0, -1) : 行);

/**
 * 开栏行拆成四段：缩进、记号、info 首词（语言）、info 剩下的部分、行尾那个 `\r`。
 *
 * "要不要猜语言"（`blocks.ts` 的 `有效开栏`）与"用户从下拉里选了一门"（`schema.ts` 的
 * `改语言`）两处都得按同一份口径改这一行。各写一份正则的结果就是：一份认 `\r` 一份不认，
 * CRLF 的文件里其中一处静默什么也不做。
 *
 * 重建时**丢掉语言前面的那段空白**：CommonMark 定义 info 串就不含首尾空白，没有任何一家
 * 渲染器看得出差别，留着它只会让"改语言"变成"改语言 + 保留一串看不见的空格"。
 */
export function 拆开栏(
  开: string
): { 缩: string; 记: string; 词: string; 尾: string; 车: string } | null {
  const m = /^(\s*)(`{3,}|~{3,})([^\r\n]*)(\r?)$/.exec(开);
  if (!m) return null;
  const [, 缩 = "", 记 = "", 余 = "", 车 = ""] = m;
  const 词们 = 余.split(/\s+/).filter((x) => x !== "");
  return { 缩, 记, 词: 词们[0] ?? "", 尾: 词们.slice(1).join(" "), 车 };
}

/** 把 `拆开栏` 的结果拼回一行开栏 */
export function 拼开栏(拆: { 缩: string; 记: string; 词: string; 尾: string; 车: string }): string {
  const 语 = [拆.词, 拆.尾].filter(Boolean).join(" ");
  // 语言被清空、作者却写过别的（`// 注释`）：留一个空格，别把围栏和它粘成 ```` ```// 注释 ````
  return 拆.缩 + 拆.记 + (语 && !拆.词 ? " " + 语 : 语) + 拆.车;
}

export type 围栏行 = { 记号: string; 语言: string; 可闭栏: boolean };

/**
 * 一行围栏。info 串可以是多词（`` ```rust // 注释 ``、`` ```js showLineNumbers ``），
 * 语言只取第一个词——真机栽过：早先按"一个不带空格的词"匹配整行，用户往开栏行里加一句
 * 注释，整块就静默退回源文本，看着像"渲染坏了"。
 *
 * `可闭栏` 是 CommonMark 的规矩：闭栏必须同种字符、不短于开栏、**且不带 info**。
 */
export function 围栏行of(line: string | undefined): 围栏行 | null {
  const m = FENCE.exec(净行(line ?? ""));
  if (!m) return null;
  const [, 记号 = "", 余 = ""] = m;
  const 干净 = 余.trim();
  if (记号[0] === "`" && 干净.includes("`")) return null; // 反引号围栏的 info 里不许有反引号
  return { 记号, 语言: 干净.split(/\s+/)[0] ?? "", 可闭栏: 干净 === "" };
}

/**
 * **内核那一侧**认的闭栏（`crates/md-kernel` 的 `take_code`）：只剥**空格**（不限个数）、
 * 以开栏那串记号开头、记号之后到行尾全空。三条都不是可以"差不多"的，每一条都对应一次
 * "我们以为在这儿闭了、内核没在这儿闭"——而块的边界是内核定的，我们一切早就是**把用户
 * 写过的行丢掉**：
 *
 * - 制表符不算缩进：```` \t``` ```` 内核不当闭栏，从前 `FENCE` 的 `\s{0,3}` 当；
 * - **比开栏更长的同种记号也不算**：内核看的是"记号长度之后有没有东西"，```` ```` ````
 *   对 ```` ``` ```` 来说就是"有"（CommonMark 这里比内核严，但**落盘的字节跟内核走**）；
 * - 带 info 的行不是闭栏。
 */
function 是内核闭栏(行: string, 记号: string): boolean {
  const 剥 = 净行(行).replace(/^ +/, "");
  return 剥.startsWith(记号) && 剥.slice(记号.length).trim() === "";
}

export type 围栏拆 = {
  /** 开栏行，原样（含前导缩进与 info 串） */
  开: string;
  /** 围栏之间的正文行。`[]` 与 `[""]` 是两件事：前者是 ``` 紧挨 ```，后者中间有一个空行 */
  身: string[];
  /** 闭栏行；null = 没找到闭栏 */
  闭: string | null;
};

/**
 * 拆开一段围栏。首行不是开栏 → `null`（这一块不归这条路管）。
 *
 * **闭栏只可能是最后一行**。从前从文末往前找"第一处像闭栏的"，理由是"用户往代码里打一道
 * ` ``` ` 时后半截不许掉出代码块"——那个理由由账本本身负责（开栏与闭栏一旦进了 attrs，
 * 打字改动的只是正文，两道围栏不会跟着动），而这里猜错的代价是实打实的：内核给的那个
 * 代码块 `raw` **就停在它自己的闭栏上**，闭栏之后不会再有行，所以任何"不在末行的闭栏"
 * 都只可能是我们与内核判据不一致的产物，切下去就是把 `raw` 的后半截丢了。
 *
 * 找不到末行闭栏 → `闭: null`，调用方按"没闭栏"处理（不接管、原样回写），绝不凭空补一道
 * ` ``` `——那是替用户写字节。
 */
export function 拆围栏(源: string): 围栏拆 | null {
  const 行 = 源.split("\n");
  const 开 = 围栏行of(行[0]);
  // 只判"首行是不是开栏"。单独一道 ` ``` ` 也算一个（空正文的）代码块：CommonMark、
  // 内核与显示形都这么认，这里多要一个"至少两行"就把那种块打回源文本了。
  if (!开) return null;
  const 末 = 行.length - 1;
  if (末 > 0 && 是内核闭栏(行[末]!, 开.记号)) {
    return { 开: 行[0]!, 身: 行.slice(1, 末), 闭: 行[末]! };
  }
  return { 开: 行[0]!, 身: 行.slice(1), 闭: null };
}

/**
 * 拆回去。`身` 为空数组时不产出中间那个换行——` ``` ` 紧挨 ` ``` ` 与"中间一个空行"
 * 是两种字节，都拼成同一个形状的话，用户删掉代码块里最后一行就会多出一个空行。
 */
export function 拼围栏(拆: { 开: string; 身: string[]; 闭: string | null }): string {
  const 身 = 拆.身.join("\n");
  if (拆.闭 === null) return 拆.身.length ? 拆.开 + "\n" + 身 : 拆.开;
  return 拆.身.length ? 拆.开 + "\n" + 身 + "\n" + 拆.闭 : 拆.开 + "\n" + 拆.闭;
}
