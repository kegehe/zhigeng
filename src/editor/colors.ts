/**
 * 文字色与底色的调色板。
 *
 * 这里的色值会**原样写进 `.md`**（`<span style="color:#e5534b">`），所以只能是字面量：
 * 写 `var(--md-red)` 的话，文件拿到 Obsidian / VS Code / 别人的机器上就是一串不认识的
 * 字符。也正因为如此，这个文件在 `scripts/guard.mjs` 的样式禁止清单里单独放行——
 * 护栏禁的是"组件里随手写颜色"，不是"落盘要一个真色值"。
 *
 * 对比度是**量过的**：六个色值在亮纸底（--bg-base）上 2.25–3.31:1、夜底上 4.25–6.24:1。
 * 它不跟随主题、也不承诺 AA——那是用户自己拣的颜色，替他换一套等于把选择权收回去；而
 * "亮/暗各一套色值"要在文件里存两份，与"一个色值走遍所有编辑器"互斥。单值色在两套底上的
 * 上限本来就在 3.8 左右（L≈0.20 时两边相等），要更高的对比度只能回到语义色名那条路。
 */
export type 色 = { id: string; 名: string; hex: string };

export const 调色板: 色[] = [
  { id: "red", 名: "红", hex: "#e5534b" },
  { id: "amber", 名: "橙", hex: "#d29922" },
  { id: "green", 名: "绿", hex: "#3fb950" },
  { id: "blue", 名: "蓝", hex: "#4a9eff" },
  { id: "purple", 名: "紫", hex: "#a371f7" },
  { id: "gray", 名: "灰", hex: "#8b949e" },
];

/**
 * 底色用同一个色号加 8 位十六进制的 alpha（`#e5534b33`）。
 *
 * 不用固定的浅色：浅色底在暗色主题下是一块发光的白斑。半透明色叠在纸底或夜底上，
 * 两套主题各自成立，而文件里仍然只有一个色值——不用为"暗色模式"再存第二份。
 */
export function 底色of(hex: string): string {
  return `${hex}33`;
}
