/**
 * 块级公式的 `$$` 账本。与 `fence.ts` 是同一个形状：
 *
 * - 显示面只画围栏之间的公式体；
 * - 编辑面只装公式体，两道 `$$` 进 attrs，保存时按原样拼回去。
 *
 * 只认**首末两行各自只有 `$$`** 的那一种写法。单行 `$$ E = mc^2 $$`、行内混着正文的
 * `$$x$$ y`、以及没有闭栏的公式都不接管——拼不回原字节的形状宁可按源文本回显。
 * 首末行里的空白与 `\r` 都留在账本里，因此 CRLF 文件也逐字节还原。
 */

export type 公式拆 = {
  /** 开栏行，原样 */
  开: string;
  /** 两道 `$$` 之间的正文行；`[]` 与 `[""]` 是两种字节 */
  身: string[];
  /** 闭栏行，原样 */
  闭: string;
};

const 净行 = (行: string) => (行.endsWith("\r") ? 行.slice(0, -1) : 行);
const 是公式栏 = (行: string | undefined) => 净行(行 ?? "").trim() === "$$";

export function 拆公式(源: string): 公式拆 | null {
  const 行 = 源.split("\n");
  const 末 = 行.length - 1;
  // 至少要有开、闭两行；单行 `$$` 是没闭栏的公式，按内核的边界也不该在这里补一道
  if (末 < 1 || !是公式栏(行[0]) || !是公式栏(行[末])) return null;
  return { 开: 行[0]!, 身: 行.slice(1, 末), 闭: 行[末]! };
}

export function 拼公式(拆: 公式拆): string {
  return [拆.开, ...拆.身, 拆.闭].join("\n");
}
