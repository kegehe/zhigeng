import { describe, expect, it } from "vitest";
import { 拼开栏, 拼围栏, 拆围栏, 拆开栏 } from "./fence";

/**
 * 围栏的拆与拼。**这是"点进代码块不再看到 Markdown"的地基**：开栏行与闭栏行存进账本，
 * 节点正文只装围栏之间那段代码，保存时再由这里拼回去。
 *
 * 所以这组测试判的不是"画得好不好"，而是**拆完再拼必须逐字节等于原样**——
 * 差一个换行就是改用户的文件。
 */

const 回 = (源: string) => {
  const 拆 = 拆围栏(源);
  expect(拆, 源).not.toBeNull();
  return 拼围栏(拆!);
};

describe("围栏拆分", () => {
  it("首行不是围栏就不归这条路管", () => {
    expect(拆围栏("一段正文")).toBeNull();
    expect(拆围栏("``")).toBeNull(); // 两道反引号不是围栏
    expect(拆围栏("只有 一行")).toBeNull();
  });

  it("拆完拼回去逐字节相同（各种合法形状各来一发）", () => {
    for (const 源 of [
      "```\n甲\n```",
      "```js\nconst a = 1;\n```",
      "```\n\n```", // 中间一个空行
      "```\n```", // 中间零行
      "````\n内含 ``` 的一行\n````", // 四道围栏包住三道
      "~~~\n波浪号\n~~~",
      "  ```py\n缩进两格\n  ```", // 缩进围栏（前导空格算在开栏行里）
      "```rust // 注释\nfn main() {}\n```", // info 串带空格
      "```js showLineNumbers\nlet x = 1;\n```",
      "```\n甲\n乙\n\n丙\n```", // 正文里有空行
      "```\n\t制表符开头\n```",
    ]) {
      expect(回(源), 源).toBe(源);
    }
  });

  it("`零行` 与 `一个空行` 是两种字节，不能拼成同一种", () => {
    expect(拆围栏("```\n```")!.身).toEqual([]);
    expect(拆围栏("```\n\n```")!.身).toEqual([""]);
    expect(拼围栏({ 开: "```", 身: [], 闭: "```" })).toBe("```\n```");
    expect(拼围栏({ 开: "```", 身: [""], 闭: "```" })).toBe("```\n\n```");
  });

  it("闭栏从最后一行往前找：正文里那道 ``` 不算闭栏", () => {
    // 用户往代码里打一道 ``` 是常事（写 Markdown 的代码块本身）。就近找闭栏的话，
    // 后半截会掉出代码块——显示形与账本必须都判"最后一行才是闭栏"
    const 拆 = 拆围栏("```\n甲\n```\n乙\n```")!;
    expect(拆.身).toEqual(["甲", "```", "乙"]);
    expect(拆.闭).toBe("```");
    expect(拼围栏(拆)).toBe("```\n甲\n```\n乙\n```");
  });

  it("没闭栏：闭 = null，正文到文末（CommonMark 与内核同判）", () => {
    const 拆 = 拆围栏("```go\nfunc main() {")!;
    expect(拆.闭).toBeNull();
    expect(拆.身).toEqual(["func main() {"]);
    // 拼回去也不许凭空造一道闭栏
    expect(拼围栏(拆)).toBe("```go\nfunc main() {");
    // 单独一道开栏 = 一个空正文的代码块，那种形状显示形一直画得出来，别改出口径
    expect(拆围栏("```go")).toEqual({ 开: "```go", 身: [], 闭: null });
    expect(拼围栏(拆围栏("```go")!)).toBe("```go");
  });

  it("闭栏带 info 就不是闭栏；反引号围栏的 info 里不许有反引号", () => {
    // ` ```js ` 当闭栏不成立 → 它是正文的一部分
    expect(拆围栏("```\n甲\n```js")!.闭).toBeNull();
    expect(拆围栏("```a`b\n甲\n```")).toBeNull();
  });

  it("闭栏的判据与内核逐条对齐（不一致就是丢用户的行）", () => {
    expect(拆围栏("````\n甲\n```")!.闭).toBeNull(); // 三道闭不了四道的开栏
    expect(拆围栏("~~~\n甲\n```")!.闭).toBeNull(); // 混用字符不算闭栏
    /**
     * **比开栏更长的同种记号，内核不认它当闭栏**：`take_code` 判的是"记号长度之后有没有东西"，
     * ```` ```` ```` 对 ```` ``` ```` 来说后面还有个反引号。CommonMark 在这里比内核宽，
     * 但**块的边界是内核定的**——我们照 CommonMark 切就会在内核以为"还没闭"的地方切一刀，
     * 后面那几行从节点里掉出去，用户改一个字它们就不在文件里了。
     */
    expect(拆围栏("```\n甲\n````")!.闭).toBeNull();
    expect(拼围栏(拆围栏("```\n甲\n````")!)).toBe("```\n甲\n````");
    /**
     * 制表符不是缩进：内核只 `trim_start_matches(' ')`。从前 `FENCE` 的 `\s{0,3}` 把
     * ```` \t``` ```` 当闭栏，于是"内核的一道闭栏（四空格那行）"变成了我们的第二道，
     * 中间的行整段丢掉。四空格的闭栏反过来内核认（它剥空格不限个数），我们也得认。
     */
    expect(拆围栏("```\n甲\n\t```\n乙\n    ```")!.身).toEqual(["甲", "\t```", "乙"]);
    expect(拆围栏("```\n甲\n    ```")!.闭).toBe("    ```");
    // 制表符缩进的那道既不是内核的闭栏、又不在末行 → 整块判成没闭栏（不接管，原样回写）
    expect(拆围栏("```\n甲\n\t```")!.闭).toBeNull();
  });

  it("闭栏只可能在末行：不在末行的那道不算闭栏", () => {
    // 内核给一个代码块的 raw 就停在它自己的闭栏上，闭栏之后不会再有行。
    // 所以"末行不是闭栏"只有一种解释：我们与内核判的不是同一道围栏。
    expect(拆围栏("```\n甲\n```\n乙")!.闭).toBeNull();
    // 没闭栏时拼回去也不许多出一道
    expect(拼围栏(拆围栏("```\n甲\n```\n乙")!)).toBe("```\n甲\n```\n乙");
  });

  it("CRLF 的文件照样接管，且拼回去仍是 CRLF", () => {
    // 判据得跳过行尾那个 `\r`（`.` 不认它、`$` 又不在串尾），但**存进账本的必须是原样那一行**
    const 源 = "```js\r\nlet a = 1;\r\n```";
    const 拆 = 拆围栏(源)!;
    expect(拆.开).toBe("```js\r");
    expect(拆.闭).toBe("```");
    // 正文行**带着自己的 `\r` 原样存**——剥了它就等于把 CRLF 文件改成 LF
    expect(拆.身).toEqual(["let a = 1;\r"]);
    expect(拼围栏(拆)).toBe(源);
    // 空正文的两种形状在 CRLF 下也是两种字节
    expect(拼围栏(拆围栏("```js\r\n\r\n```")!)).toBe("```js\r\n\r\n```");
    expect(拼围栏(拆围栏("```js\r\n```")!)).toBe("```js\r\n```");
  });

  it("开栏行的拆与拼：改语言不许吃掉作者写的尾巴", () => {
    const 改 = (开: string, 值: string) => 拼开栏({ ...拆开栏(开)!, 词: 值 });
    expect(改("```rust // 标记", "go")).toBe("```go // 标记");
    // 选"无"是清语言，不是删注释
    expect(改("```rust // 标记", "")).toBe("``` // 标记");
    expect(改("```rust", "")).toBe("```");
    expect(改("  ~~~toml showLineNumbers", "yml")).toBe("  ~~~yml showLineNumbers");
    // CRLF 的开栏行：改完 `\r` 还在，否则这一行从 CRLF 变成 LF（混行尾）
    expect(改("```js\r", "ts")).toBe("```ts\r");
    expect(拆开栏("一段正文")).toBeNull();
  });
});
