import { describe, expect, it } from "vitest";
import { 拆围栏, 拼围栏 } from "./fence";

/**
 * 围栏的拆与拼。**这是"点进代码块不再看到 Markdown"的地基**：开栏行与闭栏行存进账本，
 * 节点正文只装围栏之间那段代码，保存时再由这里拼回去。
 *
 * 所以这组测试判的不是"画得好不好"，而是**拆完再拼必须逐字节等于原样**——
 * 差一个换行就是改用户的文件。
 */

const 回 = (源: string) => {
  const 拆 = 拆围栏(源);
  expect(拆, 源).not.toBeNull();
  return 拼围栏(拆!);
};

describe("围栏拆分", () => {
  it("首行不是围栏就不归这条路管", () => {
    expect(拆围栏("一段正文")).toBeNull();
    expect(拆围栏("``")).toBeNull(); // 两道反引号不是围栏
    expect(拆围栏("只有 一行")).toBeNull();
  });

  it("拆完拼回去逐字节相同（各种合法形状各来一发）", () => {
    for (const 源 of [
      "```\n甲\n```",
      "```js\nconst a = 1;\n```",
      "```\n\n```", // 中间一个空行
      "```\n```", // 中间零行
      "````\n内含 ``` 的一行\n````", // 四道围栏包住三道
      "~~~\n波浪号\n~~~",
      "  ```py\n缩进两格\n  ```", // 缩进围栏（前导空格算在开栏行里）
      "```rust // 注释\nfn main() {}\n```", // info 串带空格
      "```js showLineNumbers\nlet x = 1;\n```",
      "```\n甲\n乙\n\n丙\n```", // 正文里有空行
      "```\n\t制表符开头\n```",
    ]) {
      expect(回(源), 源).toBe(源);
    }
  });

  it("`零行` 与 `一个空行` 是两种字节，不能拼成同一种", () => {
    expect(拆围栏("```\n```")!.身).toEqual([]);
    expect(拆围栏("```\n\n```")!.身).toEqual([""]);
    expect(拼围栏({ 开: "```", 身: [], 闭: "```" })).toBe("```\n```");
    expect(拼围栏({ 开: "```", 身: [""], 闭: "```" })).toBe("```\n\n```");
  });

  it("闭栏从最后一行往前找：正文里那道 ``` 不算闭栏", () => {
    // 用户往代码里打一道 ``` 是常事（写 Markdown 的代码块本身）。就近找闭栏的话，
    // 后半截会掉出代码块——显示形与账本必须都判"最后一行才是闭栏"
    const 拆 = 拆围栏("```\n甲\n```\n乙\n```")!;
    expect(拆.身).toEqual(["甲", "```", "乙"]);
    expect(拆.闭).toBe("```");
    expect(拼围栏(拆)).toBe("```\n甲\n```\n乙\n```");
  });

  it("没闭栏：闭 = null，正文到文末（CommonMark 与内核同判）", () => {
    const 拆 = 拆围栏("```go\nfunc main() {")!;
    expect(拆.闭).toBeNull();
    expect(拆.身).toEqual(["func main() {"]);
    // 拼回去也不许凭空造一道闭栏
    expect(拼围栏(拆)).toBe("```go\nfunc main() {");
    // 单独一道开栏 = 一个空正文的代码块，那种形状显示形一直画得出来，别改出口径
    expect(拆围栏("```go")).toEqual({ 开: "```go", 身: [], 闭: null });
    expect(拼围栏(拆围栏("```go")!)).toBe("```go");
  });

  it("闭栏带 info 就不是闭栏；反引号围栏的 info 里不许有反引号", () => {
    // ` ```js ` 当闭栏不成立 → 它是正文的一部分
    expect(拆围栏("```\n甲\n```js")!.闭).toBeNull();
    expect(拆围栏("```a`b\n甲\n```")).toBeNull();
  });

  it("闭栏必须同种字符、不短于开栏", () => {
    expect(拆围栏("````\n甲\n```")!.闭).toBeNull(); // 三道闭不了四道的开栏
    expect(拆围栏("~~~\n甲\n```")!.闭).toBeNull(); // 混用字符不算闭栏
    expect(拆围栏("```\n甲\n````")!.闭).toBe("````"); // 更长可以
  });
});
