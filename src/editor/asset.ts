/**
 * 资产引用（`![[…]]` / `![…](…)`）的拆与拼。**这是"图片块单面化"的地基**：
 * 文件里那一行既要是屏幕上那张缩略图，也要能被原样拼回字节，所以判据只许有一份。
 *
 * 与 `fence.ts` 同一条理由：显示形与序列化各自实现一遍，早晚分叉，而这里的分叉
 * 等于改用户的字节。三处消费者：`blocks.ts` 的载入与落盘、`schema.ts` 的图片 NodeView、
 * 粘贴时新建的那一块。
 *
 * 只管**引用本身那一段**。块锚点（` ^b-…`）与 CRLF 的行尾 `\r` 由调用方 `blocks.ts`
 * 负责——它们住在引用括号的**外面**，而且 `\r` 在锚点之后，谁把它们算进这一行，
 * 拼回去就会把它们挪到错的位置上。
 *
 * 只接管**指向本库 `attachments/` 的那一种**。裸文件名（`![[图.png]]`）与相对路径
 * （`![](../x.png)`）要的是全库文件名解析——docs/05 明记着没做，这里靠猜把它糊上，
 * 结果就是"图指着不存在的地方"，那一块继续显示源文本才是诚实的。
 */

export type 资产引用 = {
  /** wiki 形（Obsidian 的 `![[目标|别名]]`）还是 Markdown 形（`![别名](目标)`） */
  形: "wiki" | "md";
  目标: string;
  别名: string;
  /** 区分 `![[a.png]]` 与 `![[a.png|]]`：后者写了那根竖线，就是用户打的字 */
  有别名: boolean;
  /** 行首缩进。它是字节，拼回去要一个不少 */
  前: string;
  /** 闭括号之后的尾随空白（常见于块锚点被摘掉之后留下的空格） */
  后: string;
};

/**
 * `![[目标|别名]]`。竖线左边必须有内容（`![[|]]` 那种空目标内核判不成 image，
 * `render.test.ts` 钉着），右边可以空。
 *
 * **别名里允许再出现竖线**：内核算目标用的是 `split('|').next()`，所以 `![[a.png|左|右]]`
 * 的目标是 `a.png`、别名是 `左|右`。判据若比内核严，用户在图注里打一根竖线就会把这块
 * 送回"显示源文本"那一面——既违反单面这根杆子，也违反"屏幕上说的与落盘的是同一句话"。
 * 方括号与换行仍然不许：它们会让这一行再也拆不回来。
 */
const WIKI = /^([ \t]*)!\[\[([^|\]\r\n]+)(\|([^\]\r\n]*))?\]\]([ \t]*)$/;
/**
 * `![别名](目标)`。**收紧到没有标题、没有尖括号包住的路径**：`![a](p "标题")` 与
 * `![a](<p>)` 都还有我们没搬进 attrs 的字节，接管了就拼不回去——那就别接管。
 */
const MD = /^([ \t]*)!\[([^()\[\]\r\n]*)\]\(([^()\s<>\r\n]+)\)([ \t]*)$/;

/** 这一行是不是一个**完整的、能原样拼回去的**图片引用。整行必须只有它自己。 */
export function 拆资产引用(行: string): 资产引用 | null {
  const 威 = WIKI.exec(行);
  if (威) {
    return {
      形: "wiki",
      目标: 威[2]!,
      别名: 威[4] ?? "",
      有别名: 威[3] !== undefined,
      前: 威[1]!,
      后: 威[5]!,
    };
  }
  const 马 = MD.exec(行);
  if (马) {
    return {
      形: "md",
      目标: 马[3]!,
      别名: 马[2]!,
      // Markdown 形里 `![a]` 与 `![]` 是两种字节，但那对空方括号不该被当成"用户写了别名"
      有别名: 马[2]!.length > 0,
      前: 马[1]!,
      后: 马[4]!,
    };
  }
  return null;
}

/** 拼回文件里的那一行。**与 `拆资产引用` 必须互为逆函数**，测试逐条钉着。 */
export function 拼资产引用(拆: 资产引用): string {
  const 身 =
    拆.形 === "wiki"
      ? `![[${拆.目标}${拆.有别名 ? `|${拆.别名}` : ""}]]`
      : `![${拆.别名}](${拆.目标})`;
  return 拆.前 + 身 + 拆.后;
}

/**
 * 目标指向本库资产目录吗。`attachments/…` 与前导斜杠的 `/attachments/…`（docs/02 的
 * Vault 根相对写法）都算；带 `..` 的一律不算——那已经越出"我们的资产"这个前提，
 * 除了后端 `Vault::resolve` 那道墙，界面也不该为它画一张注定破图的缩略图。
 */
export function 是库内资产(目标: string): boolean {
  const 干 = 目标.replace(/\\/g, "/").replace(/^\/+/, "");
  if (干.split("/").some((段) => 段 === ".." || 段 === ".")) return false;
  return 干.length > "attachments/".length && 干.startsWith("attachments/");
}

/**
 * attrs → 这一份判据要的拆形。序列化（`blocks.ts`）与写侧自检（图片 NodeView 的图注框）
 * 共用它，免得两处各写一遍"别名/竖线怎么算"——那正是本仓库已经付过三次学费的分叉。
 */
export function 拆自attrs(属性: Record<string, unknown>): 资产引用 {
  const 别名 = String(属性.mdAlt ?? "");
  return {
    形: 属性.mdWiki === false ? "md" : "wiki",
    目标: String(属性.mdSrc ?? ""),
    别名,
    // 别名一旦有内容，无论那个标志怎么来的都必须写回去：宁可多一根竖线，不可丢用户打的字
    有别名: Boolean(属性.mdNamed) || 别名 !== "",
    前: String(属性.mdLead ?? ""),
    后: String(属性.mdTail ?? ""),
  };
}

/** 粘贴与插入时新建那一块的形状：wiki 形、不带别名、前面没缩进、后面没尾巴。 */
export function 新引用(目标: string): 资产引用 {
  return { 形: "wiki", 目标, 别名: "", 有别名: false, 前: "", 后: "" };
}

/**
 * 这一份拆出来的东西**拼回去还能被同一份判据拆回来**吗。
 *
 * 写侧（剪贴板 `parseHTML`、图注输入框）与读侧（装载文件）必须过同一道闸，否则就会出现
 * "写进去的一行，下次打开再也认不出是图"——真测过：外部 HTML 带一个
 * `data-md-src="a.png]]\n\n# 标题\n![[b"`，落盘直接凭空多出一个标题块。
 * 这里不另写一套字符黑名单，就用这一对函数自己验自己：拼回去再拆一遍，形状、目标、别名、
 * 那根竖线在不在，四项全等才算无损。
 */
export function 可无损(拆: 资产引用): boolean {
  const 回 = 拆资产引用(拼资产引用(拆));
  return (
    回 !== null &&
    回.形 === 拆.形 &&
    回.目标 === 拆.目标 &&
    回.别名 === 拆.别名 &&
    回.有别名 === 拆.有别名 &&
    回.前 === 拆.前 &&
    回.后 === 拆.后
  );
}

/**
 * 把用户打的图注收到"这一行还拆得回来"的范围里。
 *
 * 换行与方括号在两种形状里都是终结符，留着就等于把这块图永久降级成源文本；Markdown 形里
 * 圆括号还会把链接截断。**竖线不动**——wiki 形的别名允许它（见 `WIKI` 那条），用户在图注里
 * 打"左|右"是要留住的。收过之后再过一次 `可无损`，两道闸用的是同一份判据。
 */
export function 收图注(值: string, 形: "wiki" | "md"): string {
  let 收 = 值.replace(/[[\]\r\n]/g, "");
  if (形 === "md") 收 = 收.replace(/[()]/g, "");
  return 收.trim();
}
