/**
 * 资产引用（`![[…]]` / `![…](…)`）的拆与拼。**这是"图片块单面化"的地基**：
 * 文件里那一行既要是屏幕上那张缩略图，也要能被原样拼回字节，所以判据只许有一份。
 *
 * 与 `fence.ts` 同一条理由：显示形与序列化各自实现一遍，早晚分叉，而这里的分叉
 * 等于改用户的字节。三处消费者：`blocks.ts` 的载入与落盘、`schema.ts` 的图片 NodeView、
 * 粘贴时新建的那一块。
 *
 * 只管**引用本身那一段**。块锚点（` ^b-…`）与 CRLF 的行尾 `\r` 由调用方 `blocks.ts`
 * 负责——它们住在引用括号的**外面**，而且 `\r` 在锚点之后，谁把它们算进这一行，
 * 拼回去就会把它们挪到错的位置上。
 *
 * 只接管**指向本库 `attachments/` 的那一种**。裸文件名（`![[图.png]]`）与相对路径
 * （`![](../x.png)`）要的是全库文件名解析——docs/05 明记着没做，这里靠猜把它糊上，
 * 结果就是"图指着不存在的地方"，那一块继续显示源文本才是诚实的。
 */

export type 资产引用 = {
  /** wiki 形（Obsidian 的 `![[目标|别名]]`）还是 Markdown 形（`![别名](目标)`） */
  形: "wiki" | "md";
  目标: string;
  别名: string;
  /** 区分 `![[a.png]]` 与 `![[a.png|]]`：后者写了那根竖线，就是用户打的字 */
  有别名: boolean;
  /** 行首缩进。它是字节，拼回去要一个不少 */
  前: string;
  /** 闭括号之后的尾随空白（常见于块锚点被摘掉之后留下的空格） */
  后: string;
};

/**
 * `![[目标|别名]]`。竖线左边必须有内容（`![[|]]` 那种空目标内核判不成 image，
 * `render.test.ts` 钉着），右边可以空。目标里不许有竖线、方括号与换行。
 */
const WIKI = /^([ \t]*)!\[\[([^|\]\r\n]+)(\|([^|\]\r\n]*))?\]\]([ \t]*)$/;
/**
 * `![别名](目标)`。**收紧到没有标题、没有尖括号包住的路径**：`![a](p "标题")` 与
 * `![a](<p>)` 都还有我们没搬进 attrs 的字节，接管了就拼不回去——那就别接管。
 */
const MD = /^([ \t]*)!\[([^()\[\]\r\n]*)\]\(([^()\s<>\r\n]+)\)([ \t]*)$/;

/** 这一行是不是一个**完整的、能原样拼回去的**图片引用。整行必须只有它自己。 */
export function 拆资产引用(行: string): 资产引用 | null {
  const 威 = WIKI.exec(行);
  if (威) {
    return {
      形: "wiki",
      目标: 威[2]!,
      别名: 威[4] ?? "",
      有别名: 威[3] !== undefined,
      前: 威[1]!,
      后: 威[5]!,
    };
  }
  const 马 = MD.exec(行);
  if (马) {
    return {
      形: "md",
      目标: 马[3]!,
      别名: 马[2]!,
      // Markdown 形里 `![a]` 与 `![]` 是两种字节，但那对空方括号不该被当成"用户写了别名"
      有别名: 马[2]!.length > 0,
      前: 马[1]!,
      后: 马[4]!,
    };
  }
  return null;
}

/** 拼回文件里的那一行。**与 `拆资产引用` 必须互为逆函数**，测试逐条钉着。 */
export function 拼资产引用(拆: 资产引用): string {
  const 身 =
    拆.形 === "wiki"
      ? `![[${拆.目标}${拆.有别名 ? `|${拆.别名}` : ""}]]`
      : `![${拆.别名}](${拆.目标})`;
  return 拆.前 + 身 + 拆.后;
}

/**
 * 目标指向本库资产目录吗。`attachments/…` 与前导斜杠的 `/attachments/…`（docs/02 的
 * Vault 根相对写法）都算；带 `..` 的一律不算——那已经越出"我们的资产"这个前提，
 * 除了后端 `Vault::resolve` 那道墙，界面也不该为它画一张注定破图的缩略图。
 */
export function 是库内资产(目标: string): boolean {
  const 干 = 目标.replace(/\\/g, "/").replace(/^\/+/, "");
  if (干.split("/").some((段) => 段 === ".." || 段 === ".")) return false;
  return 干.length > "attachments/".length && 干.startsWith("attachments/");
}

/** 粘贴与插入时新建那一块的形状：wiki 形、不带别名、前面没缩进、后面没尾巴。 */
export function 新引用(目标: string): 资产引用 {
  return { 形: "wiki", 目标, 别名: "", 有别名: false, 前: "", 后: "" };
}
