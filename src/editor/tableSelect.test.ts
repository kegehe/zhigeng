import { describe, expect, it } from "vitest";
import {
  单格,
  归一,
  含,
  格数,
  多格,
  覆盖行,
  覆盖列,
  左上,
  夹住,
} from "./tableSelect";

/** 矩形选区是批量动作的唯一判据：算错一格就是改错用户的字节 */
describe("矩形归一化", () => {
  it("四个方向拖出来的都是同一个矩形", () => {
    const 期望 = { r0: 1, c0: 2, r1: 3, c1: 4 };
    expect(归一({ 行: 1, 列: 2 }, { 行: 3, 列: 4 })).toEqual(期望);
    expect(归一({ 行: 3, 列: 4 }, { 行: 1, 列: 2 })).toEqual(期望);
    expect(归一({ 行: 3, 列: 2 }, { 行: 1, 列: 4 })).toEqual(期望);
    expect(归一({ 行: 1, 列: 4 }, { 行: 3, 列: 2 })).toEqual(期望);
  });

  it("单格矩形含端点，格数是 1 而不是 0", () => {
    const 一 = 单格({ 行: 2, 列: 3 });
    expect(一).toEqual({ r0: 2, c0: 3, r1: 2, c1: 3 });
    expect(格数(一)).toBe(1);
    expect(含(一, { 行: 2, 列: 3 })).toBe(true);
    expect(含(一, { 行: 2, 列: 4 })).toBe(false);
  });
});

describe("多格判定", () => {
  it("单格不算多格：那时光标在格子里，退格该删字符而不是清空整格", () => {
    expect(多格(单格({ 行: 0, 列: 0 }))).toBe(false);
    expect(多格(null)).toBe(false);
  });

  it("一行两列就已经是多格", () => {
    expect(多格(归一({ 行: 0, 列: 0 }, { 行: 0, 列: 1 }))).toBe(true);
  });
});

describe("覆盖的行与列", () => {
  it("跨行跨列各算各的：删所选行与逐列对齐用的就是这两个", () => {
    const 矩 = 归一({ 行: 3, 列: 1 }, { 行: 1, 列: 2 });
    expect(覆盖行(矩)).toEqual([1, 2, 3]);
    expect(覆盖列(矩)).toEqual([1, 2]);
  });

  it("填充抄的是矩形左上角，不是光标那一格", () => {
    expect(左上(归一({ 行: 3, 列: 2 }, { 行: 1, 列: 0 }))).toEqual({ 行: 1, 列: 0 });
  });
});

describe("夹住", () => {
  it("删过行/列之后矩形跟着缩，不会指着不存在的格", () => {
    expect(夹住({ r0: 0, c0: 0, r1: 5, c1: 5 }, 3, 2)).toEqual({ r0: 0, c0: 0, r1: 2, c1: 1 });
  });

  it("整块选区已经被删掉时给 null，而不是硬夹出一个假矩形", () => {
    expect(夹住({ r0: 4, c0: 0, r1: 6, c1: 2 }, 3, 4)).toBeNull();
    expect(夹住({ r0: 0, c0: 4, r1: 1, c1: 6 }, 3, 4)).toBeNull();
  });

  it("夹完仍要能判多格：从多格夹成单格时批量档自动退回单格档", () => {
    const 夹后 = 夹住({ r0: 0, c0: 0, r1: 0, c1: 3 }, 3, 1);
    expect(夹后).toEqual({ r0: 0, c0: 0, r1: 0, c1: 0 });
    expect(多格(夹后)).toBe(false);
  });
});
