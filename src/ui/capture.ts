/**
 * 速记窗怎么认 `note://capture-indexed` 的回执。
 *
 * 后端那条事件的负载是 `{ rel, ok }`：**带 rel** 才能把"这一笔"和"上一笔还没落地的
 * 回执"分开。只发路径列表 / 空数组时，两笔速记挨得太近就只能猜，猜错会把上一笔的
 * 失败报在这一条头上。
 *
 * 回执可能比 `capture_text` 的返回值先到：那时 `待.rel` 还是空串，先按 rel 存起来，
 * 等命令返回再用 `res.rel` 认领。所以"归属"这一档只有三种答案——本笔、上一笔、
 * 还不知道（先收下）。
 */
export type 索引回执 = { rel: string; ok: boolean };

/**
 * 这条回执是不是当前这一笔的。
 *
 * `待rel` 为空 = 命令还没返回、路径还不知道：这时只能先收下并按 rel 存着，
 * 等命令返回后认领。`待rel` 已知时严格按路径比：不相等就是上一笔的，不能算过来。
 */
export function 回执属于本笔(待rel: string, 回执rel: string): boolean {
  return 待rel === "" || 待rel === 回执rel;
}
