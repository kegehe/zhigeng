import type { DirBranch } from "./tree";

/**
 * 侧栏树菜单里**该有哪些项**只在这里判一次。
 *
 * 行尾「…」与右键是两个入口，落到同一份判据上：各写一份的话，右键一个语义顶层目录
 * 也会给出"删除"，而语义顶层正是**不该让用户改删**的那三条。
 * 这里只回答"有没有这一项"；点了做什么、后端能不能做，由 App 调用的命令决定。
 */

export type 菜单键 =
  | "建子目录"
  | "建笔记"
  | "改名目录"
  | "删空目录"
  | "打开"
  | "改名笔记"
  | "归档"
  | "取消归档"
  | "回收"
  | "顶层建笔记"
  | "顶层建目录";

export type 菜单项 =
  | { 类: "动作"; 键: 菜单键; 字样: string; 危险?: boolean }
  | { 类: "提示"; 字样: string };

/** 顶层三条是语义目录：能往里建东西，但改名/删除不是用户该做的事 */
// 大小写不敏感：NTFS 上 `Notes` 与 `notes` 是同一个目录，后端保留名也按这个口径拒
export const 是语义顶层 = (b: DirBranch) =>
  b.depth === 0 && ["notes", "inbox", "archive"].includes(b.path.toLowerCase());

/**
 * 目录：建东西永远给（语义顶层也是目录）；改名/删除只给**空**的非语义目录。
 * `空 === null` 是"还在问后端"——这期间两样都不给，不猜。
 */
export function 目录菜单(目: DirBranch, 空: boolean | null): 菜单项[] {
  const 项: 菜单项[] = [
    { 类: "动作", 键: "建子目录", 字样: "新建子目录" },
    { 类: "动作", 键: "建笔记", 字样: "在此新建笔记" },
  ];
  if (是语义顶层(目)) return 项;
  if (空 === true) {
    项.push({ 类: "动作", 键: "改名目录", 字样: "重命名" });
    项.push({ 类: "动作", 键: "删空目录", 字样: "删除空目录", 危险: true });
  } else if (空 === false) {
    // 说出来比给一个点了会报错的入口强
    项.push({ 类: "提示", 字样: "这一版只改空目录——先把它里面的东西挪走" });
  }
  return 项;
}

/** 笔记：归档是按所在目录判的（[02]：归档状态 = 在不在 `archive/`） */
export function 笔记菜单(rel: string): 菜单项[] {
  const 归档中 = rel.replace(/\\/g, "/").startsWith("archive/");
  return [
    { 类: "动作", 键: "打开", 字样: "打开" },
    { 类: "动作", 键: "改名笔记", 字样: "重命名" },
    { 类: "动作", 键: 归档中 ? "取消归档" : "归档", 字样: 归档中 ? "取消归档" : "移到归档" },
    { 类: "动作", 键: "回收", 字样: "移到回收站", 危险: true },
  ];
}

/** 树的空白处：只有"往库里建东西"这一件事，没有可操作的行 */
export const 空白菜单 = (): 菜单项[] => [
  { 类: "动作", 键: "顶层建笔记", 字样: "新建笔记" },
  { 类: "动作", 键: "顶层建目录", 字样: "新建目录" },
];

/**
 * 指针处弹出：贴边时往回收。
 * 菜单可能有一截落在窗口外，等于那几项点不到——**宁可盖住指针也别出界**。
 */
export function 菜单坐标(
  指针: { x: number; y: number },
  视口: { 宽: number; 高: number },
  预估 = { 宽: 176, 高: 240 }
) {
  return {
    left: Math.max(0, Math.min(指针.x, 视口.宽 - 预估.宽)),
    top: Math.max(0, Math.min(指针.y, 视口.高 - 预估.高)),
  };
}
