/**
 * 目录树拖拽的**纯判定层**：给定"被拖的是哪一行、指针落在哪一行的哪个位置"，
 * 算出落点与要写盘的层序列。
 *
 * 单独立一个模块有两个原因：一是这套规矩（缝隙算给谁的层、目录行的中间带才是"移进去"）
 * 全靠边角情况成立，必须在没有 DOM 的地方也测得到；二是 App.tsx 已经够长，
 * 把判据留在组件里等于把它和 `elementFromPoint` 绑死，测不了。
 *
 * 一条贯穿的口径：**缝隙属于它下面那一行**。树是展平渲染的，目录行下面紧跟着的就是它的
 * 孩子，所以"目录行与它的第一个孩子之间"这条缝天然等于"插成这个目录的第一个孩子"，
 * 不需要额外规则去猜用户的层级意图。
 */

/** 一行在拖拽眼里的样子。由 App 从 DOM 现取，不养第二份状态 */
export type 行 = {
  /** 与 React key 同一条：目录 `d:<path>`、笔记 `n:<rel>` */
  键: string;
  /** 归一后的父路径，库根是空串 */
  父: string;
  /** 层内名字：目录是路径末段（不是显示名，顶层那三条显示成中文），笔记是文件名 */
  名: string;
  是目录: boolean;
  /** 目录：自己的完整路径；笔记：rel */
  自身: string;
};

/**
 * 落点。
 * - `gap`：插进 `父` 这一层，排在 `前` 之前；`前` 为 null 表示这层末尾
 * - `into`：移进某个目录（只有"笔记落到目录行的中间带"才成立）
 */
export type 落点 =
  | { kind: "gap"; 父: string; 前: string | null }
  | { kind: "into"; 目录: string }
  | null;

/** 一次拖拽要落盘的东西。跨层那一跳同时改两层：源层少掉它、目标层多出它 */
export type 拖拽动作 =
  | { 类型: "重排"; 层: { parent: string; names: string[] } }
  | { 类型: "移动"; 新路径: string; 层: { parent: string; names: string[] }[] };

/** 目录行的中间带占多高：上下各留这条缝给"插到它前面 / 后面" */
const 缝 = 0.25;

/**
 * 指针落在哪。`偏移` 是指针相对命中行顶部的距离，`高` 是那一行的高度。
 * 无效组合直接判 null，不回退到"最近的合法落点"。
 */
export function 判落点(
  被拖: 行,
  命中: 行 | null,
  下一: 行 | null,
  偏移: number,
  高: number
): 落点 {
  if (!命中 || 高 <= 0) return null;
  const 比 = 偏移 / 高;
  // 只有"笔记落到别的目录的行上"才有"移进去"这一档；目录落到目录上只算同级重排
  const 可移入 = 命中.是目录 && !被拖.是目录 && 命中.自身 !== 被拖.父;
  const 缝隙 = (后面: boolean): 落点 => {
    if (!后面) return { kind: "gap", 父: 命中.父, 前: 命中.名 };
    // 后面这条缝归下面那一行：目录展开时那行通常是它的第一个孩子
    if (下一) return { kind: "gap", 父: 下一.父, 前: 下一.名 };
    return { kind: "gap", 父: 命中.父, 前: null };
  };
  const 落: 落点 = 可移入 && 比 >= 缝 && 比 <= 1 - 缝
    ? { kind: "into", 目录: 命中.自身 }
    : 可移入
      ? 缝隙(比 > 0.5)
      : 缝隙(比 >= 0.5);
  return 合法(被拖, 落);
}

/** 同一层内的序列：摘掉被拖的那个，再插到指定位置前（null = 末尾） */
export function 重排(
  现状: readonly string[],
  被拖名: string,
  插到: string | null
): string[] {
  const 剩 = 去掉(现状, 被拖名);
  if (插到 === null) return [...剩, 被拖名];
  const 位 = 剩.indexOf(插到);
  if (位 < 0) return [...剩, 被拖名];
  return [...剩.slice(0, 位), 被拖名, ...剩.slice(位)];
}

/** 某一层的现状：显示出来的序列 + 这一层到底被自定义过没有 */
export type 层现状 = { 序列: readonly string[]; 存过: boolean };

/**
 * 落点 → 要写盘的动作。`读层` 给的是某一层的现状（`tree.ts` 的 `层内名字` + 存没存过）。
 *
 * 移进目录时放在目标层的**最前面**：刚落进来的那条要一眼看得见，而不是沉到一长串末尾。
 * 源层只在它本来就有自定义序时才写——没排过序的层不该被一次"拖走一篇"顺手固化成
 * 名单，那会让以后新建的笔记沉到那层末尾（未排过的排在排过的后面），
 * 而默认规则下它本该按更新时间排在最前。
 */
export function 算动作(
  被拖: 行,
  落: 落点,
  读层: (父: string) => 层现状
): 拖拽动作 | null {
  if (!落) return null;
  if (落.kind === "into") {
    const 层们 = [{ parent: 落.目录, names: [被拖.名, ...去掉(读层(落.目录).序列, 被拖.名)] }];
    if (读层(被拖.父).存过) 层们.unshift({ parent: 被拖.父, names: 去掉(读层(被拖.父).序列, 被拖.名) });
    return { 类型: "移动", 新路径: 拼路径(落.目录, 被拖.名), 层: 层们 };
  }
  if (落.父 === 被拖.父) {
    const 现状 = [...读层(被拖.父).序列];
    const 新序 = 重排(现状, 被拖.名, 落.前);
    // 位置没变就别写盘：一次无事的拖拽不该产生一次落盘
    if (新序.join("\u0000") === 现状.join("\u0000")) return null;
    return { 类型: "重排", 层: { parent: 被拖.父, names: 新序 } };
  }
  const 层们 = [{ parent: 落.父, names: 重排(读层(落.父).序列, 被拖.名, 落.前) }];
  if (读层(被拖.父).存过) 层们.unshift({ parent: 被拖.父, names: 去掉(读层(被拖.父).序列, 被拖.名) });
  return { 类型: "移动", 新路径: 拼路径(落.父, 被拖.名), 层: 层们 };
}

/** 三条"看起来能拖、其实什么都没变"，外加一条"拖进去会换了物种" */
function 合法(被拖: 行, 落: 落点): 落点 {
  if (!落) return null;
  if (被拖.是目录) {
    // 档 2 里目录只能同级重排：换父要搬整棵子树，那是下一档的事
    if (落.kind === "into" || 落.父 !== 被拖.父) return null;
    return 落.前 === 被拖.名 ? null : 落;
  }
  const 目标父 = 落.kind === "into" ? 落.目录 : 落.父;
  if (是视图层(目标父)) return null;
  if (落.kind === "into") return 落.目录 === 被拖.父 ? null : 落;
  return 落.前 === 被拖.名 ? null : 落;
}

/**
 * 与 `crates/note-core/src/vault.rs` 的 `VIEWS_DIR` 对齐；改那边要改这里。
 *
 * 视图定义文件不是普通笔记：`kind_of_rel` 按目录判 `note_kind='view'`，一篇笔记被拖进
 * `views/` 就**当场变成视图定义**——从列表与搜索里消失，而它的正文一个字节都没改。
 * 这种"换个位置就换物种"的事不该由一次拖拽触发，所以直接不给落点。
 */
const 视图目录 = "views";
const 是视图层 = (父: string) => 父 === 视图目录 || 父.startsWith(`${视图目录}/`);

const 去掉 = (现状: readonly string[], 名: string) => 现状.filter((n) => n !== 名);

const 拼路径 = (父: string, 名: string) => (父 ? `${父}/${名}` : 名);
